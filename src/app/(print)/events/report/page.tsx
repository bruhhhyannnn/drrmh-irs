function HeadcountSection({ summary }: { summary: Summary }) {
  const rows = summary.headcount.rows;
  const total = rows.reduce((sum, r) => sum + r.count, 0);
  return (
    <Section
      title="Headcount"
      note={`${total.toLocaleString()} people · fields at 0 are not listed`}
    >
      {rows.length ? (
        <div
          className="grid grid-flow-col grid-cols-2 gap-x-8"
          style={{ gridTemplateRows: `repeat(${Math.ceil(rows.length / 2)}, auto)` }}
        >
          {rows.map((r) => (
            <div
              key={r.id}
              className={cn(
                ROW,
                'grid grid-cols-[minmax(0,1fr)_52px_44px] items-center gap-2 py-1.75'
              )}
            >
              <span className="text-[15px] leading-[1.3] font-medium">{r.name}</span>
              <span className="font-landing-mono text-right text-[15px] font-bold">
                {r.count.toLocaleString()}
              </span>
              <span className="font-landing-mono text-right text-[13px] font-medium text-gray-500">
                {total ? `${Math.round((r.count / total) * 100)}%` : '0%'}
              </span>
            </div>
          ))}
        </div>
      ) : (
        <p className="py-3 text-[14px] text-gray-500">No people counted.</p>
      )}
    </Section>
  );
}

