function ChartBox({
  title,
  subtitle,
  legend,
  children,
}: {
  title: string;
  subtitle: string;
  legend?: React.ReactNode;
  children: React.ReactNode;
}) {
  return (
    <div className="flex min-w-0 flex-col gap-3.5 rounded-xl border border-gray-300 p-4 break-inside-avoid">
      <div className="flex flex-wrap items-start justify-between gap-2">
        <div className="flex flex-col gap-0.5">
          <h3 className="text-[15px] font-bold">{title}</h3>
          <span className="text-[12px] text-gray-500">{subtitle}</span>
        </div>
        {legend}
      </div>
      {children}
    </div>
  );
}

function AnalyticsSection({ summary, compare }: { summary: Summary; compare: Summary | null }) {
  const both = compare ? [summary, compare] : [summary];
  const scale = timelineScale(both);
  const max = firstReportScale(both);
  const other = new Map(compare?.firstReport.map((r) => [r.name, r.minutes]));
  const minutes = (m: number | null | undefined) =>
    m === null ? 'No report' : m === undefined ? '—' : `${m} min`;
  const legend = compare && <SeriesLegend a={shortLabel(summary)} b={shortLabel(compare)} />;
  const start = summary.start ? format(summary.start, 'h:mm a') : 'first report';
  return (
    <Section
      title="Analytics"
      note={
        compare
          ? `${shortLabel(summary)} against ${shortLabel(compare)} where both exist`
          : undefined
      }
    >
      <div className="grid grid-cols-2 gap-3.5 pt-3.5">
        <ChartBox
          title="Reports received"
          subtitle={`Per ${scale.binMinutes} minutes from the ${start} start`}
          legend={legend}
        >
          <ColumnChart
            label="Reports received over time"
            labels={timelineLabels(summary, scale)}
            series={[
              { values: timelineOf(summary, scale), color: SERIES.a },
              ...(compare ? [{ values: timelineOf(compare, scale), color: SERIES.b }] : []),
            ]}
          />
        </ChartBox>
        <ChartBox
          title="Time to first report"
          subtitle="Minutes after the start, by cluster"
          legend={legend}
        >
          <RankedBars
            max={max}
            compact
            nameWidth="w-20"
            valueWidth="w-28"
            rows={summary.firstReport.map((r) => ({
              key: r.id,
              name: r.name,
              values: [
                {
                  value: r.minutes,
                  label: minutes(r.minutes),
                  color: SERIES.a,
                  muted: r.minutes === null,
                },
                ...(compare
                  ? [
                      {
                        value: other.get(r.name) ?? null,
                        label: minutes(other.get(r.name)),
                        color: SERIES.b,
                      },
                    ]
                  : []),
              ],
            }))}
          />
        </ChartBox>
        <ChartBox
          title="Casualties by condition"
          subtitle={plural(summary.totals.casualties, 'casualty', 'casualties')}
        >
          <Donut
            rows={summary.casualtiesByCondition}
            total={summary.totals.casualties}
            unit="casualties"
            compact
          />
        </ChartBox>
        <ChartBox
          title="Structural damage"
          subtitle={`${plural(summary.damage.unitsReported, 'unit', 'units')} reported · ${summary.damage.withDamage.length} with damage`}
        >
          <DamageChart rows={summary.damage.byCondition} withDamage={summary.damage.withDamage} />
        </ChartBox>
      </div>
    </Section>
  );
}
