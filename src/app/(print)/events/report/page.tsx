// The event report (A4 portrait): every casualty, missing person, cluster and unit, the
// comparison with the previous drill, and the analytics, without the app shell. It opens the
// print dialog once loaded, where it is saved as PDF. Chrome prints the running header and
// "Page x of y" from @page margin boxes; the on-screen preview shows them on each sheet.

export default function EventReportPage() {
  return (
    <Suspense>
      <EventReport />
    </Suspense>
  );
}

/** A CSS string literal for `content:`. */
const cssString = (text: string) => JSON.stringify(text);

function EventReport() {
  const eventId = useSearchParams().get('id') ?? undefined;
  const { userProfile } = useAuthStore();
  const { data: source, isPending, error } = useEventSummarySource(eventId);
  const summary = useSummary(source);
  const { data: options, isPending: optionsPending } = useCampusEventOptions(
    source?.event.campus_id
  );
  const startedAt = source?.event.started_at ? new Date(source.event.started_at) : null;
  // The comparison is with the previous drill at the same campus, when there is one.
  const previous = options?.find(
    (o) => o.id !== eventId && o.started_at && startedAt && new Date(o.started_at) < startedAt
  );
  const { data: previousSource, isPending: previousPending } = useEventSummarySource(previous?.id);
  const compare = useSummary(previous ? previousSource : null);
  const [generatedAt] = useState(() => new Date());
  const printed = useRef(false);

  const ready = !!summary && !optionsPending && (!previous || (!previousPending && !!compare));

  useEffect(() => {
    if (!ready || !summary || printed.current) return;
    printed.current = true;
    document.title = `${summary.source.event.name} — ${summary.source.event.campus.name} report`;
    // Wait for the fonts and logos so the first print isn't missing them.
    void document.fonts.ready.then(() => setTimeout(() => window.print(), 400));
  }, [ready, summary]);

  if (error || (!isPending && !source)) {
    return (
      <Shell>
        <p className="mx-auto max-w-200 p-10 text-[15px] text-[#b42318]">
          {error
            ? `The report couldn't be loaded: ${error.message}`
            : 'This event no longer exists.'}
        </p>
      </Shell>
    );
  }
  if (!ready || !summary) {
    return (
      <Shell>
        <p
          role="status"
          className="flex items-center justify-center gap-2 p-20 text-[15px] text-gray-600"
        >
          <Loader2 size={20} aria-hidden className="text-brand-500 animate-spin" />
          Preparing the report…
        </p>
      </Shell>
    );
  }

  const { event } = summary.source;
  const title = `${event.name} — ${event.campus.name}`;
  const generated = `Generated by DRRM-H IRS on ${formatDateTime(generatedAt)}`;
  const running = `Event report · DRRM-H, ${event.campus.name}`;
  const preparedBy = personName(userProfile) || userProfile?.email || '—';
  const role = userProfile?.user_type?.name === 'Super Admin' ? 'Super admin' : 'Administrator';
  const font = figtree.style.fontFamily;

  return (
    <Shell
      toolbar={
        <div className="mx-auto flex w-full max-w-[794px] flex-wrap items-center gap-3 px-4 py-3">
          <Link
            href={`/events/details?id=${event.id}`}
            className={cn(
              'flex h-10 items-center gap-1.5 rounded-lg px-1 text-[14px] font-bold text-gray-600',
              FOCUS_RING
            )}
          >
            <ArrowLeft size={16} aria-hidden />
            Back to event
          </Link>
          <div className="flex-1" />
          <button
            type="button"
            onClick={() => window.print()}
            className={cn(
              'bg-brand-500 flex h-10 items-center gap-2 rounded-full px-4.5 text-[14px] font-bold text-white hover:brightness-92',
              FOCUS_RING
            )}
          >
            <Printer size={16} aria-hidden />
            Save as PDF
          </button>
        </div>
      }
    >
      <style>{`
        @page {
          size: A4;
          margin: 16mm 15mm 14mm;
          @top-left { content: ${cssString(title)}; font: 700 9.5pt ${font}; color: #101828; }
          @top-right { content: ${cssString(running)}; font: 500 9pt ${font}; color: #667085; }
          @bottom-left { content: ${cssString(generated)}; font: 500 9pt ${font}; color: #667085; }
          @bottom-right { content: "Page " counter(page) " of " counter(pages); font: 600 9pt ${font}; color: #344054; }
        }
        @page :first {
          @top-left { content: none; }
          @top-right { content: none; }
        }
        @media print {
          html, body { background: #fff !important; }
          * { -webkit-print-color-adjust: exact; print-color-adjust: exact; }
        }
      `}</style>

      <Sheet title={title} running={running} generated={generated} first>
        <Letterhead campus={event.campus.name} />
        <div className="flex flex-col gap-1.5">
          <span className="text-[13px] font-bold tracking-[.1em] text-gray-500 uppercase">
            Event report
          </span>
          <h1 className="text-[30px] leading-[1.15] font-extrabold">{title}</h1>
          {event.description && (
            <p className="text-[15px] leading-normal text-gray-600">{event.description}</p>
          )}
        </div>
        <div className="grid grid-cols-3 gap-px overflow-hidden rounded-xl border border-gray-300 bg-gray-300">
          {[
            ['Date', event.started_at ? formatDate(event.started_at) : 'Not set'],
            [
              'Time',
              event.started_at
                ? `${formatTime(event.started_at)}${event.ended_at ? ` – ${formatTime(event.ended_at)}` : ''}`
                : '—',
            ],
            ['Status', capitalize(event.status.name)],
            ['Quarter', event.quarter || '—'],
            ['Campus', event.campus.name],
            ['Prepared by', preparedBy],
          ].map(([label, value]) => (
            <div key={label} className="flex flex-col gap-0.5 bg-white px-3.5 py-2.5">
              <span className="text-[13px] font-semibold text-gray-500">{label}</span>
              <span className="text-[15px] leading-[1.35] font-semibold">{value}</span>
            </div>
          ))}
        </div>

        <Section
          title="Summary"
          note={
            summary.completed
              ? 'Counts at completion'
              : `Counts as of ${formatDateTime(summary.asOf)}`
          }
        >
          <div className="grid grid-cols-4 gap-2.5 pt-3">
            {[
              [
                'Total affected',
                summary.totals.people.toLocaleString(),
                `Counted in ${plural(summary.totals.clustersCounted, 'cluster', 'clusters')}`,
                '',
              ],
              [
                'Reports',
                String(summary.totals.reports),
                `From ${summary.clusters.reported} of ${plural(summary.clusters.total, 'cluster', 'clusters')}`,
                '',
              ],
              [
                'Casualties',
                String(summary.totals.casualties),
                `${summary.totals.serious} serious or worse`,
                'text-[#b42318]',
              ],
              [
                'Missing',
                String(summary.totals.missing),
                `${summary.totals.unidentified} not identified`,
                'text-[#b54708]',
              ],
            ].map(([label, value, sub, tone]) => (
              <div
                key={label}
                className="flex min-w-0 flex-col gap-1 rounded-xl border border-gray-300 px-3.5 py-3"
              >
                <span className="text-[13px] font-semibold text-gray-600">{label}</span>
                <span
                  className={cn(
                    'font-landing-mono text-[26px] leading-[1.1] font-extrabold',
                    value !== '0' && tone
                  )}
                >
                  {value}
                </span>
                <span className="text-[12px] leading-[1.35] text-gray-500">{sub}</span>
              </div>
            ))}
          </div>
        </Section>

        {compare && <CompareSection summary={summary} compare={compare} />}
      </Sheet>

      <Sheet title={title} running={running} generated={generated}>
        <ClustersSection summary={summary} />
        <HeadcountSection summary={summary} />
      </Sheet>

      <Sheet title={title} running={running} generated={generated}>
        <CasualtiesSection summary={summary} />
        <MissingSection summary={summary} />
      </Sheet>

      <Sheet title={title} running={running} generated={generated} last>
        <AnalyticsSection summary={summary} compare={compare} />
        <div className="mt-auto grid grid-cols-2 gap-12 pt-6 break-inside-avoid">
          {[
            ['Prepared by', preparedBy, `${role}, DRRM-H IRS`],
            ['Noted by', 'Name and signature', 'Head, DRRM-H Program'],
          ].map(([label, name, detail]) => (
            <div key={label} className="flex flex-col gap-1">
              <span className="text-[13px] font-semibold text-gray-500">{label}</span>
              <div className="mt-8 border-b-[1.5px] border-gray-900" />
              <span className="pt-1.5 text-[15px] font-bold">{name}</span>
              <span className="text-[13px] text-gray-500">{detail}</span>
            </div>
          ))}
        </div>
      </Sheet>
    </Shell>
  );
}

function Shell({ toolbar, children }: { toolbar?: React.ReactNode; children: React.ReactNode }) {
  return (
    <div
      className={cn(
        figtree.variable,
        splineSansMono.variable,
        'font-landing min-h-dvh bg-gray-100 text-gray-900 antialiased print:bg-white'
      )}
    >
      {toolbar && (
        <div className="sticky top-0 z-10 border-b border-gray-200 bg-white print:hidden">
          {toolbar}
        </div>
      )}
      <main className="flex flex-col items-center gap-8 px-4 py-8 print:block print:p-0">
        {children}
      </main>
    </div>
  );
}

/** One A4 page on screen; in print, its content flows and the next sheet starts a new page. */
function Sheet({
  title,
  running,
  generated,
  first,
  last,
  children,
}: {
  title: string;
  running: string;
  generated: string;
  first?: boolean;
  last?: boolean;
  children: React.ReactNode;
}) {
  return (
    <article
      className={cn(
        'flex min-h-[1123px] w-full max-w-[794px] flex-col gap-5.5 bg-white px-14 pt-12 pb-8 shadow-[0_1px_3px_rgba(0,0,0,.08),0_12px_32px_rgba(0,0,0,.08)]',
        'print:min-h-0 print:max-w-none print:gap-5 print:p-0 print:shadow-none',
        !last && 'print:break-after-page'
      )}
    >
      {!first && (
        <div className="flex items-center justify-between gap-4 border-b border-gray-300 pb-3 print:hidden">
          <span className="text-[14px] font-bold">{title}</span>
          <span className="text-[13px] font-medium text-gray-500">{running}</span>
        </div>
      )}
      <div className="flex flex-1 flex-col gap-5.5 print:gap-5">{children}</div>
      <div className="mt-auto flex items-center justify-between gap-4 border-t border-gray-300 pt-3 text-[13px] font-medium text-gray-500 print:hidden">
        <span>{generated}</span>
      </div>
    </article>
  );
}

