// One submitted assessment on A4 (`?print=<id>`): the details and scores, the action list, every
// answer, then the signatures of the assessor, the safety officer and the incident commander. It
// opens the print dialog once loaded, where it is printed or saved as PDF. The checklist text is
// always in English and Filipino here, whatever the device's checklist language.

const TH = 'text-[12px] font-bold tracking-[.04em] text-gray-600 uppercase';

export function AssessmentPrint({ id }: { id: string }) {
  const record = useMyAssessment(id);
  const isOnline = useOfflineQueueStore((s) => s.isOnline);

  if (record.isPending || !record.data) {
    return (
      <PrintShell toolbar={<PrintToolbar label="Print" back={<BackLink id={id} />} />}>
        {record.isPending && isOnline ? (
          <Loader label="Preparing the assessment…" className="py-20" />
        ) : (
          <p className="mx-auto max-w-200 p-10 text-[15px] text-error-700">
            {record.isPending
              ? "You're offline. Connect to print this assessment."
              : "This assessment isn't available. It may belong to another account, or the link is incomplete."}
          </p>
        )}
      </PrintShell>
    );
  }
  return <RecordPrint record={record.data} />;
}

function BackLink({ id }: { id: string }) {
  return (
    <AssessmentLink
      query={`?view=${id}`}
      className={cn(
        'flex h-10 items-center gap-1.5 rounded-lg px-1 text-[14px] font-bold text-gray-600',
        FOCUS_RING
      )}
    >
      <ArrowLeft size={16} aria-hidden />
      Back to assessment
    </AssessmentLink>
  );
}

function RecordPrint({ record }: { record: AssessmentRecord }) {
  const { template } = record;
  const answers: AnswerMap = Object.fromEntries(
    Object.entries(record.answers).map(([itemId, a]) => [itemId, a.answer])
  );
  const score = scoreAssessment(template, record.floor_count, record.area_type_ids, answers);
  const items = applicableItems(template, record.floor_count, record.area_type_ids);
  const applies = new Set(items.map((i) => i.id));
  const sections = template.sections.filter((s) => s.items.some((i) => applies.has(i.id)));
  const ticked = new Set(record.area_type_ids);
  const areas = template.area_types.filter((a) => ticked.has(a.id)).map((a) => a.name_en);
  const notTicked = template.area_types.filter((a) => !ticked.has(a.id)).map((a) => a.name_en);
  const [generatedAt] = useState(() => new Date());
  const printed = useRef(false);

  useEffect(() => {
    // The title names the saved PDF, so it is set on every run, not only the first.
    const previous = document.title;
    document.title = `${record.building_name} — Building Safety Assessment`;
    // Wait for the fonts and logos so the first print isn't missing them. Leaving the page
    // cancels it, even while the fonts are still loading; it prints once.
    let cancelled = false;
    let timer: ReturnType<typeof setTimeout> | undefined;
    void document.fonts.ready.then(() => {
      if (cancelled || printed.current) return;
      timer = setTimeout(() => {
        printed.current = true;
        window.print();
      }, 400);
    });
    return () => {
      cancelled = true;
      clearTimeout(timer);
      document.title = previous;
    };
  }, [record.building_name]);

  const title = record.building_name;
  const running = `Building Safety Assessment · ${formatDate(record.ended_at)}`;
  const generated = `Generated by DRRM-H IRS on ${formatDateTime(generatedAt)}`;

  return (
    <PrintShell toolbar={<PrintToolbar label="Print" back={<BackLink id={record.id} />} />}>
      <PrintPageStyle title={title} running={running} generated={generated} />

      <Sheet title={title} running={running} generated={generated} first>
        <Letterhead campus={record.campus_name} />
        <div className="flex flex-col gap-1.5">
          <span className="text-[13px] font-bold tracking-widest text-gray-500 uppercase">
            Building Safety Assessment · {template.label}
          </span>
          <h1 className="text-[30px] leading-[1.15] font-extrabold">{record.building_name}</h1>
        </div>
        <div className="grid grid-cols-3 gap-px overflow-hidden rounded-xl border border-gray-300 bg-gray-300">
          {[
            ['College or unit', record.unit_name],
            ['Cluster', record.cluster_name],
            ['Event', record.event_name ?? 'None'],
            ['Started', formatDateTime(record.started_at)],
            ['Ended', formatDateTime(record.ended_at)],
            ['Floors', String(record.floor_count)],
            ['Assessor', record.evaluator_name || '—'],
            ['Incident commander', record.incident_commander || '—'],
            ['Areas present', areas.length > 0 ? areas.join(', ') : 'None'],
          ].map(([label, value]) => (
            <div key={label} className="flex flex-col gap-0.5 bg-surface px-3.5 py-2.5">
              <span className="text-[13px] font-semibold text-gray-500">{label}</span>
              <span className="text-[15px] leading-[1.35] font-semibold">{value}</span>
            </div>
          ))}
        </div>

        {score.needsFollowUp && <FollowUpNotice score={score} sections={template.sections} />}
        <ScoresSection score={score} />
        <UnsafeSection score={score} sections={template.sections} />
        <SectionScores score={score} sections={template.sections} />
      </Sheet>

      <Sheet title={title} running={running} generated={generated} last>
        <Section
          title="Checklist answers"
          note={notTicked.length > 0 ? `Not applicable: no ${notTicked.join(', ')}` : undefined}
        >
          {sections.map((section) => (
            <SectionAnswers
              key={section.id}
              section={section}
              items={section.items.filter((i) => applies.has(i.id))}
              record={record}
            />
          ))}
        </Section>
        <Signatures record={record} />
      </Sheet>
    </PrintShell>
  );
}

const formatPercent = (t: Tally) => {
  const p = percent(t);
  return p === null ? '—' : `${p}%`;
};

const RECOVERY_TEXT = { in_place: 'In place', missing: 'Missing', na: 'N/A' };

function FollowUpNotice({
  score,
  sections,
}: {
  score: AssessmentScore;
  sections: TemplateSection[];
}) {
  const flagged = score.unsafe.filter((i) => i.flag_label);
  const sectionOf = new Map(sections.map((s) => [s.id, s]));
  return (
    <div className="rounded-xl border border-warning-200 bg-warning-50 px-4 py-3 text-[15px] text-warning-800 break-inside-avoid">
      <span className="font-bold">{flagged[0]?.flag_label}.</span> Unsafe answer on{' '}
      {flagged
        .map((i) => {
          const section = sectionOf.get(i.section_id);
          return section ? itemLabel(section, i) : i.code;
        })
        .join(', ')}
      .
    </div>
  );
}

function ScoresSection({ score }: { score: AssessmentScore }) {
  const { overall } = score;
  const recoveryState = recoveryStatus(score.pillars['rehabilitation-recovery']);
  const tiles = PILLARS.filter((p) => p.slug !== 'rehabilitation-recovery').map((pillar) => ({
    pillar,
    tally: score.pillars[pillar.slug as keyof typeof score.pillars],
  }));
  return (
    <Section
      title="Scores"
      note={`${overall.safe} of ${overall.counted} safe${overall.na > 0 ? ` · ${overall.na} N/A` : ''}`}
    >
      <div className="grid grid-cols-4 gap-2.5 pt-3 break-inside-avoid">
        <div className="bg-brand-solid flex min-w-0 flex-col gap-1 rounded-xl px-3.5 py-3 text-white">
          <span className="text-[13px] font-semibold text-white/80">Overall</span>
          <span className="font-landing-mono text-[30px] leading-[1.1] font-extrabold">
            {formatPercent(overall)}
          </span>
          <span className="text-[12px] leading-[1.35] text-white/80">Safe answers</span>
        </div>
        {tiles.map(({ pillar, tally }) => {
          const Icon = pillar.icon;
          return (
            <div
              key={pillar.slug}
              className="flex min-w-0 flex-col gap-1 rounded-xl border border-gray-300 px-3.5 py-3"
            >
              <span className="flex items-center gap-1.5 text-[13px] font-semibold text-gray-600">
                <Icon size={14} aria-hidden className="shrink-0 text-brand-700" />
                {pillar.label}
              </span>
              <span className="font-landing-mono text-[26px] leading-[1.1] font-extrabold">
                {formatPercent(tally)}
              </span>
              <span className="text-[12px] leading-[1.35] text-gray-500">
                {tally.safe} of {tally.counted} safe
              </span>
            </div>
          );
        })}
      </div>
      <p className="flex items-center gap-2 pt-3 text-[15px]">
        <span className="text-gray-600">Public Service Continuity Plan:</span>
        <span
          className={cn(
            'font-bold',
            recoveryState === 'in_place' && 'text-success-700',
            recoveryState === 'missing' && 'text-error-700',
            recoveryState === 'na' && 'text-gray-600'
          )}
        >
          {RECOVERY_TEXT[recoveryState]}
        </span>
      </p>
    </Section>
  );
}

function UnsafeSection({
  score,
  sections,
}: {
  score: AssessmentScore;
  sections: TemplateSection[];
}) {
  const groups = unsafeByPillar(score);
  const sectionOf = new Map(sections.map((s) => [s.id, s]));
  return (
    <Section title="Unsafe items" note={`${score.unsafe.length} to act on`}>
      {groups.length === 0 ? (
        <p className="pt-3 text-[15px] text-gray-600">No unsafe answers.</p>
      ) : (
        groups.map(({ pillar, items }) => {
          const info = PILLARS.find((p) => p.slug === pillar);
          return (
            <div key={pillar} className="flex flex-col pt-3">
              <span className={cn(TH, 'border-b border-gray-300 pb-1.5 break-after-avoid')}>
                {info?.name ?? pillar}
              </span>
              {items.map((item) => {
                const section = sectionOf.get(item.section_id);
                return (
                  <div
                    key={item.id}
                    className="flex gap-3 border-b border-line py-2 text-[14px] break-inside-avoid"
                  >
                    <span className="font-landing-mono w-16 shrink-0 text-[13px] font-semibold text-gray-500">
                      {section ? itemLabel(section, item) : item.code}
                    </span>
                    <Bilingual
                      en={item.prompt_en}
                      fil={item.prompt_fil}
                      language="both"
                      className="min-w-0 flex-1 leading-[1.4]"
                    />
                  </div>
                );
              })}
            </div>
          );
        })
      )}
    </Section>
  );
}

function SectionScores({
  score,
  sections,
}: {
  score: AssessmentScore;
  sections: TemplateSection[];
}) {
  const scored = sections.filter((s) => score.sections[s.id]);
  if (scored.length === 0) return null;
  return (
    <Section title="Score by section">
      <table className="w-full text-left text-[14px]">
        <thead className={cn(TH, 'border-b border-gray-300')}>
          <tr>
            <th scope="col" className="py-2 pr-2">
              Section
            </th>
            <th scope="col" className="px-2 py-2 text-right">
              Safe
            </th>
            <th scope="col" className="py-2 pl-2 text-right">
              Count
            </th>
          </tr>
        </thead>
        <tbody>
          {scored.map((section) => {
            const tally = score.sections[section.id];
            return (
              <tr key={section.id} className="border-b border-line break-inside-avoid">
                <th scope="row" className="py-1.75 pr-2 align-top font-normal">
                  <span className="flex gap-2.5">
                    <span className="font-landing-mono w-9 shrink-0 font-semibold text-gray-500">
                      {section.code}
                    </span>
                    {section.title_en}
                  </span>
                </th>
                <td className="font-landing-mono px-2 py-1.75 text-right align-top font-bold">
                  {formatPercent(tally)}
                </td>
                <td className="font-landing-mono py-1.75 pl-2 text-right align-top whitespace-nowrap text-gray-600">
                  {tally.safe} of {tally.counted}
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </Section>
  );
}

const ANSWER_TEXT: Record<AnswerValue, string> = { yes: 'Yes', no: 'No', na: 'N/A' };

function SectionAnswers({
  section,
  items,
  record,
}: {
  section: TemplateSection;
  items: TemplateItem[];
  record: AssessmentRecord;
}) {
  const comment = record.comments[section.id];
  return (
    <div className="flex flex-col pt-4">
      <div className="flex items-start gap-3 border-b border-gray-300 pb-2 break-after-avoid">
        <span className="font-landing-mono w-16 shrink-0 text-[15px] font-bold text-brand-500">
          {section.code}
        </span>
        <Bilingual
          as="h3"
          en={section.title_en}
          fil={section.title_fil}
          language="both"
          className="min-w-0 flex-1 text-[16px] leading-[1.3] font-bold"
        />
        <span className={cn(TH, 'w-14 shrink-0 pt-0.5 text-right')}>Answer</span>
      </div>
      {items.map((item) => (
        <ItemAnswer
          key={item.id}
          label={itemLabel(section, item)}
          item={item}
          answer={record.answers[item.id]}
        />
      ))}
      {comment && (
        <div className="mt-2 rounded-lg border border-gray-300 bg-gray-50 px-3.5 py-2.5 text-[14px] break-inside-avoid">
          <span className="block text-[12px] font-bold tracking-[.08em] text-gray-500 uppercase">
            Comment
          </span>
          {comment}
        </div>
      )}
    </div>
  );
}

function ItemAnswer({
  label,
  item,
  answer,
}: {
  label: string;
  item: TemplateItem;
  answer?: { answer: AnswerValue | null; remarks: string | null };
}) {
  const value = answer?.answer ?? null;
  const unsafe = item.is_scored && value != null && value !== 'na' && value !== item.safe_answer;
  return (
    <div
      className={cn(
        'flex flex-col gap-1 border-b border-line py-2 break-inside-avoid',
        unsafe && 'bg-error-50',
        item.parent_id && 'pl-5'
      )}
    >
      <div className="flex items-start gap-3">
        <span className="font-landing-mono w-16 shrink-0 pt-px text-[12px] text-gray-500">
          {label}
        </span>
        <Bilingual
          en={item.prompt_en}
          fil={item.prompt_fil}
          language="both"
          className={cn(
            'min-w-0 flex-1 text-[14px] leading-[1.4]',
            !item.is_scored && 'font-semibold'
          )}
        />
        <span
          className={cn(
            'w-14 shrink-0 text-right text-[14px] font-bold',
            !item.is_scored && 'invisible',
            value === null && 'text-gray-400',
            value === 'na' && 'text-gray-500',
            unsafe ? 'text-error-700' : value !== 'na' && value !== null && 'text-success-700'
          )}
        >
          {value === null ? '—' : ANSWER_TEXT[value]}
        </span>
      </div>
      {answer?.remarks && (
        <p className="pl-19 text-[13px] text-gray-600">
          <span className="font-semibold">Remarks:</span> {answer.remarks}
        </p>
      )}
    </div>
  );
}

function Signatures({ record }: { record: AssessmentRecord }) {
  return (
    <section className="mt-auto flex flex-col gap-3 pt-6 break-inside-avoid">
      <h2 className="border-b-2 border-gray-900 pb-2 text-[19px] leading-[1.3] font-extrabold">
        Signatures
      </h2>
      <div className="grid grid-cols-3 gap-8 pt-2">
        {[
          ['Assessor', record.evaluator_name],
          ['Safety Officer', ''],
          ['Incident Commander', record.incident_commander],
        ].map(([role, name]) => (
          <div key={role} className="flex flex-col gap-1">
            <span className="text-[13px] font-semibold text-gray-500">{role}</span>
            <div className="mt-12 border-b-[1.5px] border-gray-900" />
            <span className="pt-1.5 text-[15px] font-bold">{name || ' '}</span>
            <span className="text-[12px] text-gray-500">Signature over printed name</span>
            <div className="flex items-end gap-2 pt-5 text-[13px] text-gray-500">
              Date
              <span className="flex-1 border-b border-gray-900" />
            </div>
          </div>
        ))}
      </div>
    </section>
  );
}
